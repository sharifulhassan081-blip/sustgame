/**
 * Convert world (x, z) back to approximate real Sylhet GPS coordinates
 * so the HUD & Google-Maps-style Street View overlay display realistic Sylhet lat/lng!
 */
export function worldToSylhetGPS(x: number, z: number): { lat: number; lng: number } {
  const baseLat = 24.9052;
  const baseLng = 91.8692;
  const lng = baseLng + x * 0.0000315;
  const lat = baseLat - z * 0.0000248;
  return {
    lat: Number(lat.toFixed(5)),
    lng: Number(lng.toFixed(5)),
  };
}
